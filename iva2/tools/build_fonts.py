"""Embed the Vazirmatn subsets in css/fonts.css as base64.

Browsers refuse cross-origin font loads, and from file:// every file counts as
a different origin, so a font next to index.html may silently not load. An
embedded font always does, which matters most for the stimulus digits: they
should look the same on every computer.

Usage (from the repository root):

    python3 iva2/tools/build_fonts.py [ARABIC_WOFF2 LATIN_WOFF2]

Defaults to the Laravel site's copies in public/fonts (see tools/copy-fonts.mjs).
Vazirmatn is licensed under the SIL Open Font License; see css/LICENSE-Vazirmatn.txt.
"""
import base64
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = os.path.dirname(ROOT)

# Same unicode ranges as resources/css/app.css.
FACES = [
    ('U+0600-06FF, U+0750-077F, U+08A0-08FF, U+200C-200E, U+2010-2011, U+FB50-FDFF, U+FE70-FEFC',
     os.path.join(REPO, 'public', 'fonts', 'vazirmatn-arabic.woff2')),
    ('U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, U+2000-206F, U+2074, '
     'U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD',
     os.path.join(REPO, 'public', 'fonts', 'vazirmatn-latin.woff2')),
]


def main():
    sources = sys.argv[1:3] if len(sys.argv) == 3 else [path for _, path in FACES]
    out = ['/* Generated by tools/build_fonts.py — do not edit by hand.',
           '   Vazirmatn (SIL Open Font License 1.1, see LICENSE-Vazirmatn.txt), embedded so it loads from file://. */']
    for (ranges, _), source in zip(FACES, sources):
        with open(source, 'rb') as handle:
            data = base64.b64encode(handle.read()).decode()
        out.append('@font-face {\n'
                   "    font-family: 'Vazirmatn';\n"
                   '    font-style: normal;\n'
                   '    font-weight: 100 900;\n'
                   '    font-display: block;\n'
                   f"    src: url('data:font/woff2;base64,{data}') format('woff2');\n"
                   f'    unicode-range: {ranges};\n'
                   '}')
    with open(os.path.join(ROOT, 'css', 'fonts.css'), 'w', encoding='utf-8') as handle:
        handle.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
