    const dictionaries = { fa: fa, en: en };

    function interpolate(text, params) {
        if (!params) {
            return text;
        }
        return text.replace(/\{(\w+)\}/g, function (match, name) {
            return params[name] === undefined || params[name] === null ? match : String(params[name]);
        });
    }

    function t(lang, key, params) {
        const dictionary = dictionaries[lang] || fa;
        const text = dictionary[key] !== undefined ? dictionary[key] : fa[key] !== undefined ? fa[key] : key;
        return interpolate(text, params);
    }

    const formatters = {};

    function formatNumber(lang, value, digits) {
        if (value === null || value === undefined || !isFinite(value)) {
            return '—';
        }
        const fraction = digits === undefined ? 0 : digits;
        const key = lang + ':' + fraction;
        if (!formatters[key]) {
            formatters[key] = new Intl.NumberFormat(lang === 'fa' ? 'fa-IR' : 'en-US', {
                minimumFractionDigits: fraction,
                maximumFractionDigits: fraction,
            });
        }
        return formatters[key].format(value);
    }

    function formatDate(lang, iso) {
        if (!iso) {
            return '—';
        }
        const date = new Date(iso);
        try {
            return new Intl.DateTimeFormat(lang === 'fa' ? 'fa-IR' : 'en-GB', {
                dateStyle: 'medium',
                timeStyle: 'short',
            }).format(date);
        } catch (error) {
            return date.toLocaleString();
        }
    }

    function digitsFor(style) {
        return style === 'latin' ? { 1: '1', 2: '2' } : { 1: '۱', 2: '۲' };
    }

